import {chromium} from "playwright";
import assert from "node:assert/strict";
import axe from "axe-core";
const base=process.env.BASE_URL||"http://127.0.0.1:4173";
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:390,height:844},acceptDownloads:true});
 await page.route("https://thepeoplestally.com/**",r=>r.abort());
 await page.route("https://openamerica.io/**",r=>r.abort());
 const errors=[];
 page.on("pageerror",err=>errors.push(String(err)));
 await page.goto(base+"/results/",{waitUntil:"domcontentloaded"});
 await page.waitForFunction(()=>document.querySelector("#mReporting")?.textContent?.includes("/ 470"),null,{timeout:30000});
 await page.locator("#stateMap svg path").first().waitFor({timeout:15000});
 assert((await page.locator("#stateMap svg path").count())>=50,"US outline map should cover states");
 assert.match(await page.locator("#freshnessFlag").innerText(),/NO OBSERVED COUNTS/i);
 assert.match(await page.locator("#countQuality").innerText(),/470/);
 assert.match(await page.locator("#discrepancy").innerText(),/WITHHELD/);
 assert.match(await page.locator("#marginScatter").innerText(),/Only 0 comparable races/);
 await page.locator("#mapLayer").selectOption("senate");
 assert.match(await page.locator(".map-caption").innerText(),/Senate/i);
 await page.locator("#stateMap svg path[data-state=PA]").click();
 assert.equal(await page.locator("#state").inputValue(),"PA");
 assert.match(await page.locator("#selectedTitle").innerText(),/Pennsylvania/);
 assert.match(await page.locator("#shareView").getAttribute("href"),/state=PA/);
 await page.locator("#stateMap svg path[data-state=PA]").click();
 assert.equal(await page.locator("#state").inputValue(),"all");
 await page.locator("#state").selectOption("PA");
 await page.locator("#raceRows button.inspect-race").first().click();
 await page.locator("#raceLens:not([hidden])").waitFor();
 assert.match(await page.locator("#raceLensContent").innerText(),/Frozen model/);
 await page.locator("#closeLens").click();
 assert.equal(await page.locator("#raceLens").isHidden(),true);
 const width=await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth);
 assert(width<4,"No horizontal overflow at 390px phone viewport: "+width);
 await page.addScriptTag({content:axe.source});
 const report=await page.evaluate(async()=>axe.run(document));
 const severe=report.violations.filter(v=>["serious","critical"].includes(v.impact));
 assert.equal(severe.length,0,JSON.stringify(severe.map(v=>({id:v.id,nodes:v.nodes.slice(0,3).map(x=>x.target)}))));
 assert.deepEqual(errors,[],"No browser runtime errors");
 console.log("Results Desk v2 geographic exploration, safety, phone and accessibility gates passed");
}finally{await browser.close()}
